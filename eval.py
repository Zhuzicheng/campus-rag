# -*- coding: utf-8 -*-
"""评测脚本：对 20 道真实题目跑 RAG，输出「标准答案 vs 系统回答」供人工判分"""
import json
from rag import ask

# 20 道评测题：(问题, 标准答案) —— 答案全部来自 data/pdfs 与 data/txts 的真实内容
eval_set = [
    ("国家奖学金的奖励标准是多少？", "8000元/人/年"),
    ("省政府奖学金的奖励标准是多少？", "6000元/人/年"),
    ("申请国家奖学金对成绩排名有什么要求？", "前10%（含10%）"),
    ("申请省政府奖学金对成绩排名有什么要求？", "前15%（含15%）"),
    ("国家奖学金每学年评审几次？", "每学年一次"),
    ("学校奖学金设几个等级？", "3个等级"),
    ("一等奖学金每人每学年多少钱？", "1200元"),
    ("校长奖学金（十佳大学生）奖金是多少？", "10000元"),
    ("优秀学生的评选比例是多少？", "不超过10%"),
    ("单项奖每人奖励多少？", "600元"),
    ("请假3天以内由谁审批？", "辅导员"),
    ("请假3天以上由谁审批？", "学院分管学生工作党总支副书记"),
    ("请假期满后要办什么手续？", "到辅导员处销假"),
    ("考试期间原则上可以请假吗？", "原则上不准请假"),
    ("课堂出勤请假由谁负责？", "任课教师"),
    ("毕业生毕业设计期间外出请假先经谁同意？", "指导教师"),
    ("学生在外实习期间请假由谁批准？", "实习负责人"),
    ("学生因故不能按期入学，请假一般不得超过多久？", "两周"),
    ("休学时间是否计入修业年限？", "计入"),
    ("获学校奖学金的学生名单报哪个部门备案？", "学生工作部"),
]

results = []
for i, (q, expected) in enumerate(eval_set, 1):
    got = ask(q)
    results.append({"id": i, "question": q, "expected": expected, "got": got})
    print(f"[{i}] {q}")
    print(f"    标准: {expected}")
    print(f"    回答: {got}")
    print("-" * 70)

with open("eval_results.json", "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)
print("\n已保存 eval_results.json")
